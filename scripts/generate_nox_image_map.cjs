const fs = require('fs');
const path = require('path');
const { NOX_PRODUCT_DATA_109 } = require('../src/data/noxProductData.generated.js');

const imageMap = {};

NOX_PRODUCT_DATA_109.forEach(item => {
  const code = item.code.toUpperCase();
  const imgs = [];

  // 1. Existing JPG (실물 타일 원장)
  if (item.existingJpg) {
    imgs.push(item.existingJpg);
  }

  // 2. PDF Swatch (공식 카탈로그 색상표 견본)
  if (item.swatchImage) {
    imgs.push(item.swatchImage);
  }

  // 3. Catalog Scene (카탈로그 연출 컷)
  if (item.sceneImage) {
    imgs.push(item.sceneImage);
  }

  imageMap[code] = imgs;
});

const fileContent = `/**
 * 녹수 NOX 3종 109개 제품별 이미지 갤러리 맵
 * 순서: 원장 자재 사진 -> PDF 카탈로그 색상표 견본 -> 카탈로그 연출 공간
 * Auto-generated by scripts/generate_nox_image_map.cjs
 */

export const NOX_IMAGE_MAP = ${JSON.stringify(imageMap, null, 2)};
`;

const dest = path.join(__dirname, '..', 'src', 'data', 'noxImageMap.generated.js');
fs.writeFileSync(dest, fileContent, 'utf8');
console.log(`Generated NOX_IMAGE_MAP with ${Object.keys(imageMap).length} entries at ${dest}`);

