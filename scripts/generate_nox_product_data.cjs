const fs = require('fs');
const path = require('path');

const jsonDraftPath = path.join(__dirname, '..', 'temp_nox_extract', '사이트등록용_상품검수초안.json');
const sceneCsvPath = path.join(__dirname, '..', 'temp_nox_extract', '카탈로그_공간연출_목록.csv');

const rawDraft = JSON.parse(fs.readFileSync(jsonDraftPath, 'utf8'));
const sceneLines = fs.readFileSync(sceneCsvPath, 'utf8').split('\n').filter(Boolean);

// Parse scene mapping
const sceneMap = new Map(); // code -> scene relative path
for (let i = 1; i < sceneLines.length; i++) {
  const line = sceneLines[i].trim();
  if (!line) continue;
  
  // CSV regex parser for quoted columns
  const match = line.match(/^([^,]+),([^,]+),"([^"]+)",([^,]+),/);
  if (match) {
    const [_, lineup, page, codesStr, sceneFile] = match;
    const codes = codesStr.split(',').map(c => c.trim().toUpperCase());
    const sceneBasename = path.basename(sceneFile.trim());
    const publicScenePath = `/images/Thumbnail_Image/materials/데코타일/녹수/catalog_scenes/${lineup.trim()}/${sceneBasename}`;
    codes.forEach(c => {
      sceneMap.set(c, {
        page: Number(page),
        path: publicScenePath,
        lineup: lineup.trim()
      });
    });
  }
}

// Find existing jpgs in public directory
const existingJpgMap = new Map();
function scanJpgs(dir) {
  if (!fs.existsSync(dir)) return;
  const list = fs.readdirSync(dir);
  list.forEach(file => {
    const full = path.join(dir, file);
    if (fs.statSync(full).isDirectory()) scanJpgs(full);
    else if (file.endsWith('.jpg') || file.endsWith('.png')) {
      const code = path.basename(file, path.extname(file)).toUpperCase();
      const norm = full.replace(/\\/g, '/');
      const idx = norm.indexOf('/public/');
      const rel = idx !== -1 ? norm.substring(idx + 7) : norm;
      existingJpgMap.set(code, rel);
    }
  });
}
scanJpgs(path.join(__dirname, '..', 'public', 'images', 'Thumbnail_Image', 'materials', '데코타일', '녹수'));

const products = rawDraft.map(item => {
  const code = item.제품코드.toUpperCase();
  const swatchBasename = path.basename(item.색상표_파일);
  const swatchRel = `/images/Thumbnail_Image/materials/데코타일/녹수/pdf_swatches/${item.라인업}/${swatchBasename}`;
  const existingJpg = existingJpgMap.get(code) || null;

  const sceneInfo = sceneMap.get(code) || null;

  // Features check
  const isRusticEdge = code === 'NOW-3051' || code === 'NOW-3052';
  const isBuiltInGrout = code === 'NOT-3071' || code === 'NOT-3072' || code === 'NOT-3073';
  const isEir = code === 'NOT-31001' || code === 'NOT-31002' || code === 'NOT-31003';
  const isBigSlab = code === 'NOT-3991' || code === 'NOT-3993' || code === 'NOT-3994' || code === 'NOT-3995';
  const isParquet = code === 'NOW-3061';
  const isCrossInstall = code === 'NPT-0821' || code === 'NPT-0824' || (item.제품군 === 'SQUARE 457.2' && item.패턴명_원문.toLowerCase().includes('marble'));

  return {
    code,
    brand: '녹수',
    lineup: item.라인업,
    group: item.제품군,
    pattern: item.패턴명_원문,
    productName: item.상품명,
    thickness: `${item.두께_mm}.0T`,
    size: `${item.가로_mm} × ${item.세로_mm}mm`,
    width_mm: item.가로_mm,
    length_mm: item.세로_mm,
    pcs_per_box: item.포장수량_장,
    packing: `${item.포장수량_장}장/BOX (${item['박스면적_㎡_카탈로그']}㎡)`,
    area: `${item['박스면적_㎡_카탈로그']}㎡ (약 ${item.시공면적_평_표시})`,
    pyeong: `약 ${item.시공면적_평_표시}`,
    catalogM2: item['박스면적_㎡_카탈로그'],
    page: item.PDF페이지,
    pdf: item.원본PDF,
    priceStatus: item.가격표시, // '견적문의'
    salesStatus: item.판매상태, // '검수대기'
    inspectionNote: item.검수,
    swatchImage: swatchRel,
    existingJpg,
    sceneImage: sceneInfo ? sceneInfo.path : null,
    isRusticEdge,
    isBuiltInGrout,
    isEir,
    isBigSlab,
    isParquet,
    isCrossInstall
  };
});

const outContent = `/**
 * 녹수 NOX 3종 LVT 라인업 (오키드3000, 프라임1500, 에코홈2000) 109개 공식 카탈로그 상품 데이터
 * 기준: 오키드3000.pdf, 프라임1500.pdf, 에코홈2000.pdf, 사이트등록용_상품검수초안.json
 * Auto-generated by scripts/generate_nox_product_data.cjs
 */

export const NOX_PRODUCT_DATA_109 = ${JSON.stringify(products, null, 2)};

export const NOX_PRODUCT_BY_CODE = new Map(
  NOX_PRODUCT_DATA_109.map(p => [p.code.toUpperCase(), p])
);
`;

const destPath = path.join(__dirname, '..', 'src', 'data', 'noxProductData.generated.js');
fs.writeFileSync(destPath, outContent, 'utf8');
console.log(`Generated ${products.length} NOX products at ${destPath}`);
